// Generates src/hans-map.ts: Traditional to Simplified for every Han character the UI can show.
// Run `npm run gen:hans` after adding or changing Chinese strings in src/i18n.ts or src/kinship.ts,
// or entries of VOCAB / HANS_KIN. opencc-js is a devDependency only; it never reaches the bundle.
import { readFileSync, writeFileSync } from 'node:fs'
import * as OpenCC from 'opencc-js'
import { HANS_KIN, vocab } from '../src/hans'

const convert = OpenCC.Converter({ from: 'tw', to: 'cn' })
const han = /\p{Script=Han}/u

const chars = new Set<string>()
const addText = (s: string) => { for (const c of vocab(s)) if (han.test(c)) chars.add(c) }
for (const file of ['src/i18n.ts', 'src/kinship.ts']) {
  const src = readFileSync(new URL(`../${file}`, import.meta.url), 'utf8')
  for (const m of src.matchAll(/'((?:[^'\\\n]|\\.)*)'/g)) addText(m[1]!)
}
for (const k of Object.values(HANS_KIN)) addText(k)

const map: Record<string, string> = {}
for (const c of [...chars].sort()) {
  const s = convert(c)
  if (s !== c) map[c] = s
}
const body = Object.entries(map).map(([k, v]) => `  ${k}: '${v}',`).join('\n')
writeFileSync(new URL('../src/hans-map.ts', import.meta.url),
  `// Generated by scripts/gen-hans.ts (opencc-js tw to cn, per character). Do not edit; run \`npm run gen:hans\`.\n` +
  `export const HANS_MAP: Record<string, string> = {\n${body}\n}\n`)
console.log(`${Object.keys(map).length} characters mapped`)
